object Strings {
    var lang: String by mutableStateOf("en")
        private set

    fun setLanguage(value: String) {
        lang = if (value == "en") "en" else "zh"
    }

    private val tables = mapOf("zh" to zh, "en" to en)

    fun t(key: String, vararg args: Pair<String, Any>): String {
        var s = tables[lang]?.get(key) ?: key
        for ((k, v) in args) {
            s = s.replace("{$k}", v.toString())
        }
        return s
    }
}

fun T(key: String, vararg args: Pair<String, Any>): String = Strings.t(key, *args)
